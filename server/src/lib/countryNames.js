// Built once at module load: every code/alias, lowercased, pointing at its
// canonical name — including the canonical name itself, so looking up
// "india" and "INDIA" both resolve the same way as "IN" or "ind" do.
const LOOKUP = new Map();
for (const [name, ...codes] of COUNTRIES) {
  LOOKUP.set(name.toLowerCase(), name);
  for (const code of codes) LOOKUP.set(code.toLowerCase(), name);
}

// Title-cases a value this table doesn't recognize, rather than dropping
// or guessing at it — an unfamiliar territory name should still show up as
// something readable, just without the alias-merging real countries get.
function titleCase(value) {
  return value.replace(/\w\S*/g, (word) => word[0].toUpperCase() + word.slice(1).toLowerCase());
}

// Collapses free-text country input ("IN", "india", "ind", " India ") down
// to one canonical name ("India"). Returns null for empty/missing input so
// callers can `.filter(Boolean)` it straight into a facet list.
export function normalizeCountryName(raw) {
  if (!raw) return null;
  const trimmed = String(raw).trim();
  if (!trimmed) return null;
  return LOOKUP.get(trimmed.toLowerCase()) ?? titleCase(trimmed);
}
